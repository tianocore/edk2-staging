///////////////////////////////////////////////////////////////////////////////
// IsForbiddenByDbx - a non-signer chain certificate (intermediate or root)
// revoked in dbx by EFI_CERT_X509_SHAxxx HASH must forbid the image.
//
// Per UEFI Spec 32.5.3.3 rule B, a dbx cert-hash entry forbids the image if it
// reflects the TBS hash of ANY certificate in the signing chain, not just the
// leaf signer. IsForbiddenByDbx() reads the dbx variable via gRT->GetVariable
// (mocked here) and walks the full signing chain of the supplied PKCS#7 data.
///////////////////////////////////////////////////////////////////////////////
class ForbiddenByDbxTest : public CertHashSearchTest {
protected:
  //
  // Arrange gRT->GetVariable(dbx) to return the supplied signature-list buffer.
  // IsForbiddenByDbx calls GetVariable twice: first to query the size (data ==
  // NULL, returns EFI_BUFFER_TOO_SMALL), then to read the data.
  //
  void
  ExpectDbx (
    UINT8  *SigList,
    UINTN  SigListSize
    )
  {
    EXPECT_CALL (RtServicesMock, gRT_GetVariable)
      .WillOnce (
         DoAll (
           SetArgPointee<3>(SigListSize),
           Return (EFI_BUFFER_TOO_SMALL)
           )
         )
      .WillOnce (
         DoAll (
           SetArgPointee<3>(SigListSize),
           SetArgBuffer<4>(SigList, SigListSize),
           Return (EFI_SUCCESS)
           )
         );
  }
};

