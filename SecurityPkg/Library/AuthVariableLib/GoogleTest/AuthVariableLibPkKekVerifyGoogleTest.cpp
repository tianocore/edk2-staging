// certificate. A private variable name is used so the post-verify
// CheckSignatureListFormat() does not impose the PK/KEK X509-only constraints.
// Covers both V1 (EFI_CERT_X509_GUID) and V2 (EFI_CERT_V2_X509_GUID) layouts.
// ============================================================
